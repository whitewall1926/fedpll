def paragraph_text(paragraph: ET.Element) -> str:
    return "".join(node.text or "" for node in paragraph.iter(qn("t")))


def new_paragraph(text: str, source_ppr: ET.Element | None, is_heading: bool = False) -> ET.Element:
    paragraph = ET.Element(qn("p"))
    if source_ppr is not None:
        paragraph.append(copy.deepcopy(source_ppr))
    run = ET.SubElement(paragraph, qn("r"))
    if is_heading:
        run_props = ET.SubElement(run, qn("rPr"))
        ET.SubElement(run_props, qn("b"))
    text_node = ET.SubElement(run, qn("t"))
    text_node.set(f"{{{XML}}}space", "preserve")
    text_node.text = text
    return paragraph


def insert_supplement(source: Path, output: Path) -> None:
    with zipfile.ZipFile(source, "r") as source_zip:
        document_xml = source_zip.read("word/document.xml")
        root = ET.fromstring(document_xml)
        body = root.find(qn("body"))
        if body is None:
            raise RuntimeError("The Word document has no body element.")

        paragraphs = [child for child in list(body) if child.tag == qn("p")]
        targets = [
            paragraph
            for paragraph in paragraphs
            if paragraph_text(paragraph).strip().startswith("S8、聚合模型更新")
        ]
        if len(targets) != 1:
            raise RuntimeError(f"Expected exactly one claim-1 S8 paragraph, found {len(targets)}.")
        target = targets[0]
        insertion_index = list(body).index(target) + 1
        source_ppr = target.find(qn("pPr"))
        for index, text in enumerate(SUPPLEMENT):
            body.insert(insertion_index + index, new_paragraph(text, source_ppr, is_heading=index == 0))

        rewritten_document = ET.tostring(root, encoding="utf-8", xml_declaration=True)
        with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as output_zip:
            for item in source_zip.infolist():
                content = rewritten_document if item.filename == "word/document.xml" else source_zip.read(item.filename)
                output_zip.writestr(item, content)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("Usage: insert_claim1_supplement.py SOURCE.docx OUTPUT.docx")
    insert_supplement(Path(sys.argv[1]), Path(sys.argv[2]))
